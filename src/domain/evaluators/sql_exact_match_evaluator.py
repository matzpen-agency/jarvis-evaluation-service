"""
sql_exact_match_evaluator.py — Canonical SQL text comparison.

Both queries are parsed and re-generated by sqlglot in the connection's
dialect, so formatting, keyword case, comments, quoting style, trailing
semicolons and the engine catalog prefix (e.g. Trino's "postgres".) don't
matter. Neither do naming choices: output column aliases, table aliases,
CTE/subquery names and schema qualifiers are canonicalised, together with
every reference to them (ORDER BY revenue, x.total, ...). Anything else — column order, a
different predicate, join or function — is not an exact match. Falls back
to whitespace/case normalisation when a query can't be parsed.

Score = 1.0 if the canonical forms match, 0.0 otherwise.
"""

from __future__ import annotations

import re

import sqlglot
import sqlglot.expressions as exp
import structlog

from src.domain.entities.evaluation_context import EvaluationContext
from src.domain.entities.evaluation_result import EvaluationResult
from src.domain.evaluators.base_evaluator import BaseEvaluator
from src.domain.evaluators.sql_comparison_utils import node_arg

logger = structlog.get_logger(__name__)

PASS_THRESHOLD = 1.0  # exact normalized match required


def _normalize_sql(sql: str) -> str:
    """
    Lightly normalize SQL for comparison:
      - Lowercase
      - Remove SQL comments (-- and /* */)
      - Collapse all whitespace to single space
      - Strip trailing semicolons
    """
    sql = sql.lower()
    # Remove block comments
    sql = re.sub(r"/\*.*?\*/", " ", sql, flags=re.DOTALL)
    # Remove line comments
    sql = re.sub(r"--[^\n]*", " ", sql)
    # Collapse whitespace
    sql = re.sub(r"\s+", " ", sql).strip()
    # Strip trailing semicolons
    sql = sql.rstrip(";").strip()
    return sql


def _unalias_names(parsed: exp.Expression) -> None:
    """
    Rewrite the AST in place so that alias choices no longer matter:

      - CTEs and derived tables get positional names (__cte1, __sq1, ...)
      - table aliases are dropped and column qualifiers point at the table
      - ORDER BY / GROUP BY / HAVING references to an output alias become the
        aliased expression
      - output aliases are dropped in the outer query and made positional
        (__c1, ...) inside CTEs/subqueries, where outer references follow
    """
    renames: dict[str, str] = {}  # source alias/name (lower) → canonical name

    for i, cte in enumerate(parsed.find_all(exp.CTE), start=1):
        renames[cte.alias_or_name.lower()] = f"__cte{i}"
        cte.set("alias", exp.TableAlias(this=exp.to_identifier(f"__cte{i}")))
    for i, subquery in enumerate(parsed.find_all(exp.Subquery), start=1):
        if subquery.alias:
            renames[subquery.alias.lower()] = f"__sq{i}"
            subquery.set("alias", exp.TableAlias(this=exp.to_identifier(f"__sq{i}")))

    for table in parsed.find_all(exp.Table):
        # Engine catalog / schema qualification is a naming choice too
        table.set("catalog", None)
        table.set("db", None)
        name = table.name.lower()
        if not table.db and name in renames:  # a reference to a CTE
            table.set("this", exp.to_identifier(renames[name]))
        if table.alias:
            renames.setdefault(table.alias.lower(), renames.get(name, table.name.lower()))
            table.set("alias", None)

    # Positional output names for every CTE / derived table
    output_names: dict[tuple[str, str], str] = {}
    for node in [*parsed.find_all(exp.CTE), *parsed.find_all(exp.Subquery)]:
        source = node.alias.lower() if node.alias else None
        query = node.this
        if not source or not isinstance(query, exp.Query):
            continue
        for i, projection in enumerate(query.selects, start=1):
            if projection.alias_or_name:
                output_names[(source, projection.alias_or_name.lower())] = f"__c{i}"

    for column in list(parsed.find_all(exp.Column)):
        column.set("db", None)
        column.set("catalog", None)
        qualifier = column.table.lower()
        if not qualifier:
            continue
        source = renames.get(qualifier, qualifier)
        column.set("table", exp.to_identifier(source))
        positional = output_names.get((source, column.name.lower()))
        if positional:
            column.set("this", exp.to_identifier(positional))

    for select in parsed.find_all(exp.Select):
        aliased = {p.alias.lower(): p.unalias() for p in select.expressions if p.alias}
        for clause in ("order", "group", "having"):
            node = node_arg(select, clause)
            if node is None:
                continue
            for column in list(node.find_all(exp.Column)):
                if not column.table and column.name.lower() in aliased:
                    column.replace(aliased[column.name.lower()].copy())

        parent = select.parent
        inner_source = None
        if isinstance(parent, exp.CTE | exp.Subquery) and parent.alias:
            inner_source = parent.alias.lower()
        new_projections = []
        for i, projection in enumerate(select.expressions, start=1):
            bare = projection.unalias()
            if inner_source is not None and projection.alias:
                bare = exp.alias_(bare, f"__c{i}")
            new_projections.append(bare)
        select.set("expressions", new_projections)


def _canonical_sql(sql: str, read: str | None, write: str | None) -> str:
    try:
        parsed = sqlglot.parse_one(sql.strip().rstrip(";"), read=read)
    except Exception:
        parsed = None
    if parsed is None:
        return _normalize_sql(sql)
    try:
        _unalias_names(parsed)
        for ordered in parsed.find_all(exp.Ordered):
            # Transpiling spells out the source dialect's default NULL ordering
            # (Trino DESC → Postgres "DESC NULLS LAST"); it isn't part of the query
            ordered.set("nulls_first", None)
        canonical = parsed.sql(dialect=write)
    except Exception as exc:
        logger.debug("sql_exact_match.canonicalize_failed", error=str(exc))
        return _normalize_sql(sql)
    return _normalize_sql(canonical.replace('"', ""))


class SqlExactMatchEvaluator(BaseEvaluator):
    """
    Compares generated SQL to expected SQL after canonicalising both.
    """

    @property
    def name(self) -> str:
        return "sql_exact_match"

    async def evaluate(self, context: EvaluationContext) -> EvaluationResult:
        try:
            return self._evaluate(context)
        except Exception as exc:
            logger.error("sql_exact_match_evaluator.error", error=str(exc))
            return EvaluationResult.from_error(self.name, str(exc))

    def _evaluate(self, context: EvaluationContext) -> EvaluationResult:
        if not context.expected_sql:
            return EvaluationResult.not_applicable(self.name, "no_expected_sql")
        if not context.generated_sql:
            return EvaluationResult(
                evaluator_name=self.name,
                score=0.0,
                passed=False,
                details={"reason": "no_generated_sql"},
            )

        target = context.dialect or context.agent_dialect
        norm_exp = _canonical_sql(context.expected_sql, read=context.dialect, write=target)
        norm_gen = _canonical_sql(
            context.generated_sql, read=context.agent_dialect, write=target
        )
        passed = norm_exp == norm_gen
        score = 1.0 if passed else 0.0

        logger.debug(
            "sql_exact_match.result",
            dataset_item_id=context.dataset_item.id,
            score=score,
            passed=passed,
        )

        return EvaluationResult(
            evaluator_name=self.name,
            score=score,
            passed=passed,
            details={
                "normalized_match": passed,
                "expected_normalized": norm_exp,
                "generated_normalized": norm_gen,
            },
        )
